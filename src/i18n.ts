const strings: Record<Locale, TranslationDictionary> = { en, ru, uk };

function detectLocale(): Locale {
	try {
		const win = window as unknown as Record<string, unknown>;
		const getLangFn = win.getLanguage as (() => string) | undefined;
		const candidates = [
			typeof getLangFn === "function" ? String(getLangFn()) : "",
			moment.locale() || "",
			typeof navigator !== "undefined" ? navigator.language : ""
		];
		for (const candidate of candidates) {
			const lang = candidate.toLowerCase();
			if (lang.startsWith("ru")) return "ru";
			if (lang.startsWith("uk") || lang.startsWith("ua")) return "uk";
			if (lang) return "en";
		}
	} catch {
		// Fall back to English when the host language is unavailable.
	}
	return "en";
}

export function setLocalePreference(value: string | undefined): void {
	languagePreference = value === "ru" || value === "uk" || value === "en" ? value : "auto";
}

export function getLocale(): Locale {
	return languagePreference === "auto" ? detectLocale() : languagePreference;
}

export function tr(locale: Locale, key: TranslationKey, vars?: Record<string, string | number>): string {
	let str = strings[locale][key] || strings.en[key] || key;
	if (vars) {
		for (const [name, value] of Object.entries(vars)) {
			str = str.replace(new RegExp(`\\{${name}\\}`, "g"), String(value));
		}
	}
	return str;
}

export function t(key: TranslationKey, vars?: Record<string, string | number>): string {
	return tr(getLocale(), key, vars);
}

