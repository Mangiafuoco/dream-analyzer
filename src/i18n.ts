export interface LocaleStructure {
	dreamsSubfolder: string;
	entitiesSubfolder: string;
	indexSubfolder: string;
	entityFolders: Record<EntityCategory, string>;
}

export function getLocaleStructure(locale: Locale = getLocale()): LocaleStructure {
	return {
		dreamsSubfolder: tr(locale, "dreamsSubfolder"),
		entitiesSubfolder: tr(locale, "entitiesSubfolder"),
		indexSubfolder: tr(locale, "indexSubfolder"),
		entityFolders: {
			characters: tr(locale, "entityCharactersFolder"),
			places: tr(locale, "entityPlacesFolder"),
			objects: tr(locale, "entityObjectsFolder"),
			emotions: tr(locale, "entityEmotionsFolder"),
			symbols: tr(locale, "entitySymbolsFolder"),
			concepts: tr(locale, "entityConceptsFolder")
		}
	};
}

export function getAllLocaleStructures(): LocaleStructure[] {
	return (["ru", "uk", "en"] as Locale[]).map(getLocaleStructure);
}
