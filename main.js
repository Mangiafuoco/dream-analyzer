var ProgressNotice = class {
  constructor(totalSteps = 5) {
    this.timerId = null;
    this.totalSteps = totalSteps;
    this.step = 1;
    this.currentMessage = "";
    this.startTime = Date.now();
    this.notice = new import_obsidian8.Notice("", 0);
    this.startTimer();
  }
  setStep(step, message) {
    this.step = step;
    this.currentMessage = message;
    this.updateText();
  }
  getElapsedSeconds() {
    return Math.round((Date.now() - this.startTime) / 1e3);
  }
  startTimer() {
    this.timerId = window.setInterval(() => {
      this.updateText();
    }, 1e3);
  }
  updateText() {
    const elapsed = this.getElapsedSeconds();
    const message = `Dream Analyzer [${this.step}/${this.totalSteps}]: ${this.currentMessage} (${elapsed}s)`;
    const noticeEl = this.notice.noticeEl;
    if (noticeEl) {
      noticeEl.setText(message);
    }
  }
  close() {
    if (this.timerId !== null) {
      window.clearInterval(this.timerId);
      this.timerId = null;
    }
    this.notice.hide();
  }
};
